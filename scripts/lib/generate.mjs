// In-memory generation shared by gen-i18n.mjs (writes) and check-content.mjs (compares with the committed files).
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { LANGS, buildLangFile, eventFacts } from './model.mjs';

export const ROOT = fileURLToPath(new URL('../../', import.meta.url));
export const CONTENT_PATH = `${ROOT}content/content.json`;
export const UI_PATH = `${ROOT}content/ui.json`;
export const SOURCE_PATH = '/Volumes/workplace/WeddingInvite2/assets/copy/content.json';

export const sha256 = (buf) => createHash('sha256').update(buf).digest('hex');

export function readInputs() {
  const contentBuf = readFileSync(CONTENT_PATH);
  const uiBuf = readFileSync(UI_PATH);
  return {
    content: JSON.parse(contentBuf.toString('utf8')),
    ui: JSON.parse(uiBuf.toString('utf8')),
    contentSha256: sha256(contentBuf),
    uiSha256: sha256(uiBuf),
  };
}

/** { files: { en, hi, mai, bn }, factsTs, uiKeysTs } with `source.generatedAt` left for the writer. */
export function generate(inputs) {
  const { content, ui, contentSha256, uiSha256 } = inputs;
  const files = {};
  for (const lang of LANGS) {
    files[lang] = { ...buildLangFile(content, ui, lang), source: { contentSha256, uiSha256, generatedAt: null } };
  }
  const facts = eventFacts(content.facts);
  const wedding = facts.wedding.startUtc;
  const factsTs =
    `// Generated by scripts/gen-i18n.mjs from content/content.json (facts.events). Do not edit.\n` +
    `import type { EventKey } from '../i18n/types';\n\n` +
    `export interface EventFact { dateIso: string; time24: string; startUtc: string; venueKey: string; city: number }\n\n` +
    `export const EVENT_FACTS: Record<EventKey, EventFact> = ${JSON.stringify(facts, null, 2)};\n\n` +
    `/** The countdown target: the wedding start (IST ${facts.wedding.dateIso} ${facts.wedding.time24}). */\n` +
    `export const WEDDING_START_UTC = '${wedding}';\n\n` +
    `/** Venue key -> city index (0 Kolkata, 1 Saharsa). */\n` +
    `export const CITY_OF_VENUE: Record<string, number> = { agora: 0, roybari: 0, devresort: 1 };\n\n` +
    `export const CONTENT_SHA256 = '${contentSha256}';\n`;
  const keys = Object.keys(ui.strings);
  const uiKeysTs =
    `// Generated by scripts/gen-i18n.mjs from content/ui.json. Do not edit.\n` +
    `export const UI_KEYS = ${JSON.stringify(keys, null, 2).replace(/"/g, "'")} as const;\n\n` +
    `export type UiKey = (typeof UI_KEYS)[number];\n`;
  return { files, factsTs, uiKeysTs };
}

/** Stable comparison of two LangFiles, ignoring `source.generatedAt`. */
export function sameIgnoringTime(a, b) {
  const strip = (x) => JSON.stringify({ ...x, source: { ...x.source, generatedAt: null } });
  return strip(a) === strip(b);
}
